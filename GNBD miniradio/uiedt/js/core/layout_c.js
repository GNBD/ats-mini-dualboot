(function (root, factory) {
  const api = factory();
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (root) root.MRLayoutC = api;
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  const COLORS = { bg: "UC_BG", panel: "UC_PANEL", fg: "UC_FG", muted: "UC_MUTED",
    line: "UC_LINE", accent: "UC_ACCENT", accenth: "UC_ACCENTH", ok: "UC_OK",
    warn: "UC_WARN", red: "UC_RED", track: "UC_TRACK", hsel: "UC_HSEL", none: "UC_NONE" };
  const FONTS = { tiny: "UC_TINY", small: "UC_SMALL", large: "UC_LARGE" };
  const ALIGNS = { l: "UC_AL_L", c: "UC_AL_C", r: "UC_AL_R" };
  const TYPES = { rect: "UC_RECT", text: "UC_TEXT", bar: "UC_BAR", line: "UC_LINE_W",
    freq: "UC_FREQ", rsq: "UC_RSQ", rds: "UC_RDS", sig: "UC_SIG", bandmap: "UC_BANDMAP",
    wifi: "UC_WIFI" };
  const MASKS = { FM: "UC_M_FM", AM: "UC_M_AM", SSB: "UC_M_SSB" };

  function layerOf(w, depth, pool) {
    depth = depth || 0;
    if (w.parent && depth < 5) {
      const p = pool.find((x) => x.uid === w.parent);
      if (p && p !== w) return layerOf(p, depth + 1, pool);
    }
    return w.z == null ? 0 : w.z;
  }

  function sortedFor(items) {
    return (items || [])
      .map((w, i) => ({ w, i, z: layerOf(w, 0, items) }))
      .sort((a, b) => (a.z - b.z) || (a.i - b.i))
      .map((x) => x.w);
  }

  function widgetLine(w, forceMode) {
    if (!TYPES[w.t] || w.hidden) return null;
    const f = [".type = " + TYPES[w.t]];
    if (w.x) f.push(".x = " + Math.round(w.x));
    if (w.y) f.push(".y = " + Math.round(w.y));
    if (w.w) f.push(".w = " + Math.round(w.w));
    if (w.h) f.push(".h = " + Math.round(w.h));
    if (forceMode) {
      f.push(".modes = " + forceMode);
    } else {
      const mm = w.modes == null ? 7 : w.modes;
      if (mm !== 7) {
        const names = [];
        if (mm & 1) names.push("UC_M_FM");
        if (mm & 2) names.push("UC_M_AM");
        if (mm & 4) names.push("UC_M_SSB");
        f.push(".modes = " + (names.length ? names.join(" | ") : "0"));
      }
    }
    if (w.fill) f.push(".fill = " + COLORS[w.fill]);
    if (w.stroke) f.push(".stroke = " + COLORS[w.stroke]);
    if (w.color) f.push(".color = " + COLORS[w.color]);
    if (w.font || w.size) f.push(".font = " + FONTS[w.font || w.size]);
    if (w.align) f.push(".align = " + ALIGNS[w.align]);
    if (w.chip) f.push(".chip = 1");
    if (w.scale && w.scale !== 100) f.push(".scale = " + Math.round(w.scale));
    if (w.bind) f.push(".bind = UC_B_" + String(w.bind).toUpperCase());
    if (w.max) f.push(".max = " + w.max);
    if (w.text) f.push(".text = " + JSON.stringify(w.text));
    return "    { " + f.join(", ") + " },";
  }

  function generate(project) {
    const lines = [];
    const layouts = project.ui && project.ui.layouts;
    if (layouts) {
      for (const k of ["FM", "AM", "SSB"]) {
        for (const w of sortedFor(layouts[k] || [])) {
          const ln = widgetLine(w, MASKS[k]);
          if (ln) lines.push(ln);
        }
      }
    } else {
      for (const w of sortedFor((project.ui && project.ui.items) || [])) {
        const ln = widgetLine(w, null);
        if (ln) lines.push(ln);
      }
    }
    if (!lines.length) lines.push("    { .type = UC_RECT, .w = 0, .h = 0 },");

    return {
      name: "ui_custom_layout.h",
      content: [
        "/* Generated by MINI-radio UI Editor - do not edit by hand. */",
        "#pragma once",
        "#include \"ui_custom.h\"",
        "#define UI_CUSTOM_ENABLE 1",
        "",
        "static const uc_widget_t uc_widgets[] = {",
        lines.join("\n"),
        "};",
        "",
        "#define UC_WIDGET_COUNT ((int)(sizeof(uc_widgets) / sizeof(uc_widgets[0])))",
        "",
      ].join("\n"),
    };
  }

  return { generate, sortedFor };
});
