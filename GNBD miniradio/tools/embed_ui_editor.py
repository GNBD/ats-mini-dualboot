# Embed uiedt static files into main/ui_editor_assets.c/.h
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "uiedt")
OUT_C = os.path.join(ROOT, "main", "ui", "ui_editor_assets.c")
OUT_H = os.path.join(ROOT, "main", "ui", "ui_editor_assets.h")

SKIP = {"README.md"}


def mime(path):
    if path.endswith(".html"):
        return "text/html; charset=utf-8"
    if path.endswith(".css"):
        return "text/css; charset=utf-8"
    if path.endswith(".js"):
        return "application/javascript; charset=utf-8"
    if path.endswith(".json"):
        return "application/json"
    return "text/plain; charset=utf-8"


def escape(data):
    out = []
    for b in data:
        if b == 0x5C:
            out.append("\\\\")
        elif b == 0x22:
            out.append('\\"')
        elif b == 0x0A:
            out.append("\\n")
        elif b == 0x0D:
            out.append("\\r")
        elif b == 0x09:
            out.append("\\t")
        elif b < 0x20 or b >= 0x7F:
            out.append("\\%03o" % b)
        else:
            out.append(chr(b))
    return "".join(out)


def collect():
    files = []
    for base, dirs, names in os.walk(SRC):
        dirs[:] = [d for d in dirs if not d.startswith(".")]
        for n in sorted(names):
            if n in SKIP or n.startswith("."):
                continue
            full = os.path.join(base, n)
            rel = os.path.relpath(full, SRC).replace("\\", "/")
            files.append((rel, full))
    files.sort()
    return files


def main():
    files = collect()
    if not files:
        print("no files", file=sys.stderr)
        return 1
    with open(OUT_H, "w", encoding="utf-8", newline="\n") as h:
        h.write("/* SPDX-License-Identifier: MIT\n")
        h.write(" * Generated by tools/embed_ui_editor.py - do not edit.\n */\n")
        h.write("#pragma once\n#include <stddef.h>\n\n")
        h.write("typedef struct {\n")
        h.write("    const char *path;\n    const char *mime;\n")
        h.write("    const char *data;\n    unsigned len;\n} ui_asset_t;\n\n")
        h.write("extern const ui_asset_t ui_editor_assets[];\n")
        h.write("extern const int ui_editor_asset_count;\n")

    with open(OUT_C, "w", encoding="utf-8", newline="\n") as c:
        c.write("/* SPDX-License-Identifier: MIT\n")
        c.write(" * Generated by tools/embed_ui_editor.py - do not edit.\n */\n")
        c.write('#include "ui_editor_assets.h"\n\n')
        for i, (rel, full) in enumerate(files):
            with open(full, "rb") as f:
                data = f.read()
            c.write("static const char asset_%d[] = \"%s\";\n" % (i, escape(data)))
        c.write("\nconst ui_asset_t ui_editor_assets[] = {\n")
        for i, (rel, full) in enumerate(files):
            with open(full, "rb") as f:
                size = len(f.read())
            c.write('    { "/ui/%s", "%s", asset_%d, %d },\n' %
                    (rel, mime(rel), i, size))
        c.write("};\n\n")
        c.write("const int ui_editor_asset_count = "
                "(int)(sizeof(ui_editor_assets) / sizeof(ui_editor_assets[0]));\n")
    print("embedded %d files -> %s" % (len(files), OUT_C))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
